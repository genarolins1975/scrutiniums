/** Jornadas do ADM no build local. Conta e banco descartáveis; nunca usa credenciais reais. */
import assert from "node:assert/strict";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, join } from "node:path";
import { createRequire } from "node:module";
import { chromium } from "playwright";
import { subirServidorLocal } from "./servidor-local.mjs";
const require = createRequire(import.meta.url);
const saida = resolve(process.argv[2] ?? "docs/ux-2026-10-27/atualizacoes-adm/jornadas");
const estado = process.argv[3] ? resolve(process.argv[3]) : null;
mkdirSync(saida, { recursive: true });
const resultado = { build: readFileSync('.next/BUILD_ID', 'utf8').trim(), capturadoEm: new Date().toISOString(), verificacoes: [], capturas: [] };
const registrar = (texto) => { resultado.verificacoes.push(texto); console.log(texto); };
const s = await subirServidorLocal({ administrador: true, estadoOperacoes: estado });
const b = await chromium.launch({ executablePath: process.env.I18N_CHROMIUM_EXECUTABLE ?? '/usr/bin/chromium' });
try {
  const c = await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, reducedMotion: 'reduce' });
  await c.addCookies([s.cookie]);
  await c.addInitScript({ path: require.resolve('axe-core/axe.min.js') });
  const p = await c.newPage();
  const erros = [];
  p.on('pageerror', e => erros.push(e.message));
  await p.goto(s.origem + '/app/admin/atualizacoes', { waitUntil: 'networkidle' });
  const summary = p.locator('#tarefas > details > summary');
  await summary.focus(); await p.keyboard.press('Enter');
  assert.equal(await summary.evaluate(e => e.parentElement.open), true);
  await p.keyboard.press('Space');
  assert.equal(await summary.evaluate(e => e.parentElement.open), false);
  await summary.tap();
  const form = p.getByRole('form', { name: 'Criar tarefa manual', exact: true });
  const titulo = 'Conferir captura local de auditoria';
  await form.getByLabel('O que precisa ser feito?').fill(titulo);
  await form.getByLabel('Por quê e como resolver').fill('Tarefa sintética para verificar persistência; nenhum contato com fonte externa.');
  await form.getByLabel('Responsável', { exact: true }).fill('ADM local');
  await form.getByLabel('Prazo combinado').fill('2026-11-03');
  await form.getByLabel('Registro do ADM', { exact: true }).fill('Nota local preservada após recarregar.');
  await form.getByRole('button', { name: 'Criar tarefa', exact: true }).click();
  await p.getByRole('status').filter({ hasText: 'Tarefa criada e incluída' }).waitFor();
  await p.reload({ waitUntil: 'networkidle' });
  const li = p.locator('#tarefas li').filter({ has: p.getByText(titulo, { exact: true }) });
  await li.locator('summary').click();
  assert.equal(await li.locator('textarea[name=nota]').inputValue(), 'Nota local preservada após recarregar.');
  registrar('Criar tarefa por toque/mouse, persistir nota, responsável e prazo, atualizar página e recuperar os campos.');
  await li.getByRole('combobox', { name: 'Andamento', exact: true }).selectOption('concluida');
  await li.getByRole('button', { name: 'Salvar andamento' }).click();
  await li.waitFor({ state: 'detached' });
  assert.equal(await p.evaluate(() => document.activeElement?.id), 'andamento-fila');
  await p.getByRole('combobox', { name: 'Andamento', exact: true }).selectOption('concluida');
  await li.locator('summary').click();
  await li.getByRole('combobox', { name: 'Andamento', exact: true }).selectOption('aberta');
  await li.getByRole('button', { name: 'Salvar andamento' }).click();
  await li.waitFor({ state: 'detached' });
  await p.locator('#andamento-fila').selectOption('pendentes');
  await li.locator('summary').click();
  registrar('Concluir, reencontrar no filtro de concluídas e reabrir; foco retorna ao filtro quando a linha sai do recorte.');
  await p.route('**/api/admin/tarefas', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Falha sintética de gravação. Tente novamente.' }) }));
  await li.locator('textarea[name=nota]').fill('Texto preservado durante falha sintética.');
  await li.getByRole('button', { name: 'Salvar andamento' }).click();
  await li.getByRole('alert').waitFor();
  assert.equal(await li.locator('textarea[name=nota]').inputValue(), 'Texto preservado durante falha sintética.');
  await p.unroute('**/api/admin/tarefas');
  await li.getByRole('button', { name: 'Salvar andamento' }).click();
  await li.getByRole('status').filter({ hasText: 'Alterações salvas' }).waitFor();
  registrar('Erro de gravação anuncia falha, mantém texto e permite nova tentativa.');
  await li.locator('summary').focus();
  await p.keyboard.press('Tab'); await p.keyboard.press('Shift+Tab');
  assert.equal(await p.evaluate(() => document.activeElement?.tagName), 'SUMMARY');
  const foco = await li.locator('summary').evaluate(e => ({ estilo: getComputedStyle(e).outlineStyle, largura: parseFloat(getComputedStyle(e).outlineWidth) }));
  assert.ok(foco.estilo !== 'none' && foco.largura >= 2);
  registrar('Tab e Shift+Tab retornam ao detalhe com foco visível; Enter e Espaço abrem e fecham detalhes.');
  for (const largura of [320, 390, 768, 1440]) {
    await p.setViewportSize({ width: largura, height: 900 });
    await p.locator('#tarefas').scrollIntoViewIfNeeded();
    const horizontal = await p.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
    assert.equal(horizontal, false, `Rolagem horizontal a ${largura}`);
    const axe = await p.evaluate(async () => (await window.axe.run(document, { runOnly: { type: 'tag', values: ['wcag2a','wcag2aa','wcag21aa','wcag22aa'] } })).violations.map(v => ({ id: v.id, impacto: v.impact, alvos: v.nodes.map(n => n.target) })));
    assert.deepEqual(axe, [], `Axe ${largura}: ${JSON.stringify(axe)}`);
    const captura = `tarefas-${largura}.png`;
    await p.screenshot({ path: join(saida, captura) });
    resultado.capturas.push(captura);
  }
  registrar('Formulário e fila a 320, 390, 768 e 1440 px: sem rolagem horizontal e sem violações axe nas tags WCAG A/AA.');
  await p.setViewportSize({ width: 720, height: 450 });
  await p.evaluate(() => document.documentElement.style.fontSize = '200%');
  assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  await p.screenshot({ path: join(saida, 'texto-200.png'), fullPage: true });
  registrar('Ampliação de texto de 200% a 720 px, equivalente ao espaço CSS de desktop 1440 com zoom 200%: sem rolagem horizontal. Não substitui teste de zoom nativo em todos os navegadores.');
  await p.evaluate(() => document.documentElement.style.fontSize = '');
  await p.setViewportSize({ width: 1440, height: 900 });
  await p.getByRole('combobox', { name: 'Mostrar', exact: true }).selectOption('atencao');
  await p.getByRole('button', { name: 'Aplicar', exact: true }).click();
  await p.waitForURL('**/app/admin/atualizacoes?situacao=atencao');
  await p.goBack({ waitUntil: 'networkidle' }); await p.goForward({ waitUntil: 'networkidle' }); await p.reload({ waitUntil: 'networkidle' });
  assert.equal(await p.locator('#filtro-publicacao').inputValue(), 'atencao');
  registrar('Filtro de frescor preservado na URL, atualização, voltar e avançar.');
  // Identificadores longos são conteúdo válido: não podem alargar o celular.
  const longa = await p.evaluate(async () => {
    const r = await fetch('/api/admin/tarefas', { method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ titulo: 'Conferir identificador sintético: ' + 'captura_'.repeat(22), detalhe: '', estado: 'aberta', nota: '', responsavel: '', prazo: '', versao: 0 }) });
    return r.status;
  });
  assert.equal(longa, 200);
  await p.reload({ waitUntil: 'networkidle' });
  await p.setViewportSize({ width: 320, height: 800 });
  await p.locator('#tarefas li').filter({ hasText: 'Conferir identificador sintético:' }).scrollIntoViewIfNeeded();
  assert.equal(await p.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
  await p.screenshot({ path: join(saida, 'identificador-longo-320.png') });
  registrar('Identificador longo em tarefa manual permanece legível sem alargar a página a 320 px.');
  assert.deepEqual(erros, []);
  registrar('Sem erros JavaScript na jornada. Preferência por movimento reduzido e dispositivo com toque ativos.');
  const anonimo = await b.newContext();
  const r = await anonimo.request.get(s.origem + '/app/admin/atualizacoes', { maxRedirects: 0 });
  assert.equal(r.status(), 307);
  registrar('Sem sessão: página redireciona para entrar, preservando a restrição administrativa.');
  await anonimo.close();
  await c.close();
} finally { await b.close(); await s.encerrar(); writeFileSync(join(saida, 'jornadas.json'), JSON.stringify(resultado, null, 2) + '\n'); }
const leitor = await subirServidorLocal({ usuario: 'leitor-sem-admin' });
try {
  const r = await fetch(leitor.origem + '/app/admin/atualizacoes', { headers: { cookie: `${leitor.cookie.name}=${leitor.cookie.value}` }, redirect: 'manual' });
  assert.equal(r.status, 404);
  registrar('Conta comum: página administrativa retorna 404.');
} finally { await leitor.encerrar(); writeFileSync(join(saida, 'jornadas.json'), JSON.stringify(resultado, null, 2) + '\n'); }
